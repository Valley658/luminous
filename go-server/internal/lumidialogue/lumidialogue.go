// DefaultPath는 실행 파일 경로(go-server/bin/*.exe) 기준으로 데이터 파일
// 위치를 계산한다 - member_profiles.json/lumiprofiles.DefaultPath()와 같은 규칙.
func DefaultPath() string {
	exePath, err := os.Executable()
	if err != nil {
		return filepath.Join("lumi_data", "lumi_dialogue.json")
	}
	binDir := filepath.Dir(exePath)
	goServerDir := filepath.Dir(binDir)
	return filepath.Join(goServerDir, "lumi_data", "lumi_dialogue.json")
}

// Load는 lumi_dialogue.json을 읽어서 Defaults 위에 덮어씌운다. 필드 단위로
// 덮어쓰기 때문에, 파일에 일부 항목만 적어두거나 아예 파일이 없어도 항상
// 안전하게 동작한다(빈 값/파일 없음/JSON 문법 오류 전부 Defaults로 대체됨).
// 매 요청마다 새로 읽으므로(캐싱 없음) 서버 재시작 없이 바로 반영된다.
func Load(path string) Data {
	d := Defaults
	b, err := os.ReadFile(path)
	if err != nil {
		return d
	}
	var loaded Data
	if err := json.Unmarshal(b, &loaded); err != nil {
		return d
	}
	if loaded.CoreRules != "" {
		d.CoreRules = loaded.CoreRules
	}
	if loaded.Identity != "" {
		d.Identity = loaded.Identity
	}
	if loaded.Catchphrase != "" {
		d.Catchphrase = loaded.Catchphrase
	}
	if loaded.TonePrimer != "" {
		d.TonePrimer = loaded.TonePrimer
	}
	if loaded.SiteFacts != "" {
		d.SiteFacts = loaded.SiteFacts
	}
	if loaded.SiteHistoryFact != "" {
		d.SiteHistoryFact = loaded.SiteHistoryFact
	}
	if loaded.AdminFact != "" {
		d.AdminFact = loaded.AdminFact
	}
	if len(loaded.CreatorDeflectLines) > 0 {
		d.CreatorDeflectLines = loaded.CreatorDeflectLines
	}
	if len(loaded.SiteOriginDeflectLines) > 0 {
		d.SiteOriginDeflectLines = loaded.SiteOriginDeflectLines
	}
	if len(loaded.GalleryShowLines) > 0 {
		d.GalleryShowLines = loaded.GalleryShowLines
	}
	return d
}

// BuildSystemPrompt는 Data와, members.go에서 자동 생성되는 로스터 사실
// 문자열(rosterFacts - 이건 데이터 파일에 안 넣음, 항상 코드가 최신 멤버
// 목록으로 직접 만들어줌)을 합쳐서 최종 시스템 프롬프트를 만든다.
func BuildSystemPrompt(d Data, rosterFacts string) string {
	return d.CoreRules + "\n\n" +
		d.Identity + "\n\n" +
		d.Catchphrase + "\n\n" +
		d.TonePrimer + "\n\n" +
		rosterFacts + "\n\n" +
		d.SiteFacts + "\n\n" +
		d.SiteHistoryFact + "\n\n" +
		d.AdminFact
}
